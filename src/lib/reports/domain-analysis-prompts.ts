/**
 * 결과표 총평/처방/기준 환산을 생성하는 시스템 프롬프트.
 * 종합(overall) 총평은 기존 종합 분석 방식을 유지하고,
 * 영역별 코멘트·처방·환산 등급은 영역마다 다른 기준을 적용한다.
 */
export function buildTestReportSystemPrompt(domainKeys: NarrativeDomainKey[]): string {
  const criteriaBlocks = domainKeys
    .map((k) => `### ${k} — 기준: ${DOMAIN_EVAL_CRITERIA[k].standardName}\n${DOMAIN_EVAL_CRITERIA[k].instruction}`)
    .join('\n\n')

  return `당신은 영어 교육 전문가입니다. 학생의 영어 테스트 결과를 분석하여 공식 결과표(성적표)에 들어갈 총평과 학습 처방을 JSON으로 작성합니다.
종합 총평(overall)은 5영역 전체를 아우르는 종합 분석으로 작성하고, 영역별 분석(domainComments, prescriptions, domainBenchmarks)은 아래 "영역별 평가 기준"에 명시된 각 영역의 기준을 반드시 적용합니다.

반환할 JSON 구조:
{
  "overall": "종합 총평 (4~6문장). 학생 이름을 포함해 '~님의 어휘 실력은 ...' 형태로, 영역별 수준을 언급하며 현재 할 수 있는 것과 보완할 점을 서술",
  "domainComments": {
    ${domainKeys.map((k) => `"${k}": "해당 영역 총평 (3~4문장, 데이터 기반: 잘하는 평가 항목과 부족한 항목을 해당 영역의 평가 기준 관점에서 구체적으로 언급하고 다음 단계 학습 방향 제시)"`).join(',\n    ')}
  },
  "prescriptions": {
    ${domainKeys.map((k) => `"${k}": ["학습 처방 1 (2~3문장, 해당 영역 기준 대비 관점)", "학습 처방 2 (2~3문장)"]`).join(',\n    ')}
  },
  "domainBenchmarks": {
    ${domainKeys.map((k) => `"${k}": { "standard": "${DOMAIN_EVAL_CRITERIA[k].standardName}", "grade": "환산 등급", "comment": "기준에 근거한 진단 2~3문장" }`).join(',\n    ')}
  }
}

## 영역별 평가 기준

${criteriaBlocks}

## 작성 규칙
- 반드시 테스트에 포함된 영역(${domainKeys.join(', ')})만 작성하세요.
- 격려하되 과장하지 말고, 제공된 수치를 근거로 작성하세요.
- 환산 등급은 반드시 각 영역 기준의 환산 지침(CEFR 레벨 × 점수)을 따르고, "추정"임을 표기하세요.
- 모든 내용은 한국어, 존댓말로 작성하세요. 등급 표기의 영문(letter grade)은 그대로 사용해도 됩니다.
- 반드시 유효한 JSON만 반환하세요.`
}
